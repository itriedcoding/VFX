#!/usr/bin/env node
/*
 * VFX Studio - generates tools/api-props.lua from the official Roblox API dump.
 *
 * The headless harness used to carry a hand-written property whitelist, which
 * can only ever be as correct as the person typing it. This pulls the real
 * class/property/function tables for every class the source touches (and their
 * ancestors), so a typo like `TextTruncation` or `Enum.AutomaticSize.Y` fails
 * `npm run test` instead of failing silently inside Studio.
 *
 *   node tools/api-dump.js            # refresh from the API dump
 *   node tools/api-dump.js --offline  # regenerate from the cached file
 */
"use strict";

const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const SRC = path.join(ROOT, "src");
const CACHE = path.join(__dirname, "api-dump.json");
const OUT = path.join(__dirname, "api-props.lua");

const SOURCES = [
  "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/API-Dump.json",
  "https://raw.githubusercontent.com/MaximumADHD/Roblox-Client-Tracker/roblox/Mini-API-Dump.json",
];

// Classes the harness needs even when the source only names them indirectly.
const EXTRA = [
  "DockWidgetPluginGui", "PluginToolbar", "PluginToolbarButton", "PluginGui",
  "GuiObject", "GuiBase2d", "LayerCollector", "ScreenGui",
];

function luaFiles(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...luaFiles(p));
    else if (entry.name.endsWith(".lua")) out.push(p);
  }
  return out;
}

async function loadDump(offline) {
  if (offline || process.argv.includes("--offline")) {
    if (!fs.existsSync(CACHE)) {
      console.error("api-dump: no cache; run without --offline once");
      process.exit(1);
    }
    return { dump: JSON.parse(fs.readFileSync(CACHE, "utf8")), source: "cache" };
  }
  for (const url of SOURCES) {
    try {
      const response = await fetch(url);
      if (!response.ok) {
        console.log(`  ${url} -> ${response.status}`);
        continue;
      }
      const text = await response.text();
      const dump = JSON.parse(text);
      fs.writeFileSync(CACHE, text);
      return { dump, source: url };
    } catch (error) {
      console.log(`  ${url} -> ${error.message}`);
    }
  }
  if (fs.existsSync(CACHE)) {
    console.log("  falling back to the cached dump");
    return { dump: JSON.parse(fs.readFileSync(CACHE, "utf8")), source: "cache" };
  }
  console.error("api-dump: could not download the API dump");
  process.exit(1);
}

function collectSeeds(dump) {
  const known = new Set(dump.Classes.map((c) => c.Name));
  const seeds = new Set();
  const pattern = /(?:Instance\.new\(|:IsA\(|FindFirstChildWhichIsA\(|FindFirstChildOfClass\()\s*["']([A-Za-z0-9_]+)["']/g;
  for (const file of luaFiles(SRC)) {
    const text = fs.readFileSync(file, "utf8");
    for (const match of text.matchAll(pattern)) {
      if (known.has(match[1])) seeds.add(match[1]);
    }
  }
  for (const extra of EXTRA) if (known.has(extra)) seeds.add(extra);
  return seeds;
}

function closure(dump, seeds) {
  const byName = new Map(dump.Classes.map((c) => [c.Name, c]));
  const result = new Set(seeds);
  let grew = true;
  while (grew) {
    grew = false;
    for (const name of [...result]) {
      const cls = byName.get(name);
      if (!cls) continue;
      if (cls.Superclass && !result.has(cls.Superclass) && byName.has(cls.Superclass)) {
        result.add(cls.Superclass);
        grew = true;
      }
      // Compiler + UI touch generic typed children, e.g. FindFirstChildWhichIsA("ParticleEmitter").
    }
  }
  return [...result].sort().map((name) => byName.get(name)).filter(Boolean);
}

function luaString(value) {
  return JSON.stringify(value);
}

const IDENTIFIER = /^[A-Za-z_][A-Za-z0-9_]*$/;

function luaSet(names) {
  const valid = names.filter((n) => !n.includes(" ")); // serialized pseudo-properties
  return "{ " + valid.map((n) => (IDENTIFIER.test(n) ? `${n} = true` : `[${JSON.stringify(n)}] = true`)).join(", ") + " }";
}

(async () => {
  const { dump, source } = await loadDump(false);
  const seeds = collectSeeds(dump);
  const classes = closure(dump, seeds);
  const sourceText = luaFiles(SRC).map((f) => fs.readFileSync(f, "utf8")).join("\n");
  const usedEnums = new Set();
  for (const match of sourceText.matchAll(/Enum\.([A-Za-z_][A-Za-z0-9_]*)/g)) usedEnums.add(match[1]);
  const enums = dump.Enums.filter((e) => usedEnums.has(e.Name));

  const lines = [];
  lines.push("-- Generated by tools/api-dump.js from the Roblox API dump. Do not edit by hand.");
  lines.push(`-- Classes: ${classes.length} | Enums: ${enums.length} | Source: ${source}`);
  lines.push("API_PROPS = {}");
  for (const cls of classes) {
    const props = cls.Members.filter((m) => m.MemberType === "Property").map((m) => m.Name).sort();
    const methods = cls.Members.filter((m) => m.MemberType === "Function").map((m) => m.Name).sort();
    const events = cls.Members.filter((m) => m.MemberType === "Event").map((m) => m.Name).sort();
    lines.push(`API_PROPS[${luaString(cls.Name)}] = {`);
    lines.push(`\tSuper = ${cls.Superclass && dump.Classes.some((c) => c.Name === cls.Superclass) ? luaString(cls.Superclass) : "nil"},`);
    lines.push(`\tProps = ${luaSet(props)},`);
    lines.push(`\tMethods = ${luaSet(methods)},`);
    lines.push(`\tEvents = ${luaSet(events)},`);
    lines.push("}");
  }
  lines.push("API_ENUMS = {}");
  for (const e of enums) {
    lines.push(`API_ENUMS[${luaString(e.Name)}] = ${luaSet(e.Items.map((i) => i.Name))}`);
  }
  lines.push("");

  fs.writeFileSync(OUT, lines.join("\n"), "utf8");
  const size = (fs.statSync(OUT).size / 1024).toFixed(1);
  console.log(`api-props: ${classes.length} classes, ${enums.length} enums -> tools/api-props.lua (${size} KiB)`);
  console.log("  classes: " + classes.map((c) => c.Name).join(", "));
})();
